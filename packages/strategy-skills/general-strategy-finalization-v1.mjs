function exactAxes(rows, code) {
  if (!Array.isArray(rows) || rows.length !== INITIAL_GENERAL_STRATEGY_AXES_V1.length) fail(code);
  const byAxis = new Map(rows.map(row => [row.axis, row]));
  if (byAxis.size !== rows.length || INITIAL_GENERAL_STRATEGY_AXES_V1.some(axis => !byAxis.has(axis))) fail(code);
  return INITIAL_GENERAL_STRATEGY_AXES_V1.map(axis => byAxis.get(axis));
}

export function prepareFinalGeneralPolicyV1({ input, previousInput, sourceCandidate }) {
  [input, previousInput, sourceCandidate].forEach(verifySeal);
  if (sourceCandidate.inputHash !== previousInput.hash || hash(input.contract.sourceBinding) !== hash(previousInput.contract.sourceBinding)
    || input.contract.referenceHash !== previousInput.contract.referenceHash
    || !INITIAL_GENERAL_STRATEGY_AXES_V1.includes(sourceCandidate.axis)) fail('GENERAL_FINALIZATION_SOURCE_DRIFT');
  const reboundPolicy = structuredClone(sourceCandidate.policy);
  const priorCaseIds = reboundPolicy.caseIds; reboundPolicy.caseIds = [];
  const rebound = seal({ schema: 'strategy_case_corpus_rebound_candidate_v1', inputHash: input.hash,
    previousInputHash: previousInput.hash, sourceCandidateHash: sourceCandidate.hash,
    axis: sourceCandidate.axis, policy: reboundPolicy, priorCaseIds,
    contentChangedFields: priorCaseIds.length ? ['caseIds'] : [], caseIdsClearedBeforeNewCorpusBinding: true,
    allPriorAcceptanceInvalidated: true, runtimeAccepted: false, trainingTruth: false });
  const fix = SOURCE_FIXES[rebound.axis], proposedPolicy = structuredClone(rebound.policy);
  fix.patch(proposedPolicy);
  const audit = createBoundStrategySourceAuditV1({ input, candidate: rebound,
    checkedFields: fix.fields, findings: fix.findings, auditorClass: 'independent_source_read' });
  const correction = prepareStrategySourceCorrectionV1({ input, candidate: rebound, audit, proposedPolicy,
    proposalAuthorship: 'host_exact_source', priorPolicyHashes: [hash(rebound.policy)] });
  const developmentCaseIds = input.workspace.developmentCases.filter(row => row.policyAxes.includes(rebound.axis)).map(row => row.caseId);
  if (!developmentCaseIds.length) fail('GENERAL_FINALIZATION_DEVELOPMENT_CASE_MISSING');
  const policy = structuredClone(correction.policy); policy.caseIds = developmentCaseIds;
  const { hash: omitted, ...body } = input.contract;
  validateStrategyDraftV1({ policies: [policy] }, seal({ ...body, requiredAxes: [policy.axis] }), {
    allowedRuleRefs: input.workspace.fullFrozenSources.sources.map(source => source.ref),
    allowedCaseIds: input.workspace.developmentCases.map(row => row.caseId),
  });
  const caseBinding = seal({ schema: 'strategy_development_case_binding_v1', inputHash: input.hash, axis: policy.axis,
    parentPolicyHash: hash(correction.policy), policyHash: hash(policy), developmentCaseIds,
    heldoutIdsDisclosedToPolicy: [], decisionCasesPassed: false, runtimeAccepted: false, trainingTruth: false });
  return seal({ schema: 'strategy_finalization_candidate_v1', inputHash: input.hash, axis: policy.axis, policy,
    sourceCandidateHash: sourceCandidate.hash, reboundHash: rebound.hash, targetedAudit: audit,
    correction, caseBinding, status: 'pending_full_source_review_and_decision_cases',
    runtimeAccepted: false, trainingTruth: false });
}

export function acceptIndependentGeneralPolicySourceAuditV1({ input, candidate, reviewArtifacts }) {
  [input, candidate, ...reviewArtifacts].forEach(verifySeal);
  if (candidate.inputHash !== input.hash || reviewArtifacts.length !== 3) fail('GENERAL_FINALIZATION_REVIEW_DENOMINATOR_INVALID');
  const lifecycle = reconcileStrategyReviewOpinionsV1(reviewArtifacts.map(row => row.evidence), hash(candidate.policy));
  const fields = lifecycle.events.map(row => row.targetId.replace(/^field\./u, ''));
  if (lifecycle.open || lifecycle.uncertain || lifecycle.modelReportedClear !== REVIEW_FIELDS.length
    || hash(fields) !== hash(REVIEW_FIELDS)) fail('GENERAL_FINALIZATION_MODEL_REVIEW_NOT_CLEAR');
  const sourceByRef = new Map(input.workspace.fullFrozenSources.sources.map(source => [source.ref, source]));
  const sources = candidate.policy.ruleRefs.map(ref => {
    const source = sourceByRef.get(ref); if (!source) fail('GENERAL_FINALIZATION_SOURCE_REF_INVALID');
    return seal({ ref, sourceHash: hash(source), passages: source.passages.map(passage => ({
      spanId: passage.spanId, textHash: hash(passage.text) })) });
  });
  if (new Set(sources.map(row => row.ref)).size !== sources.length) fail('GENERAL_FINALIZATION_SOURCE_REF_DUPLICATED');
  const knownSourceConflicts = candidate.axis === 'uncertainty' ? [{
    id: 'high-ground-any-part-versus-wholly-within',
    refs: ['core.cB7X7UfOMHh3Wxn79ASF.items.1.subItems.2', 'core.cB7X7UfOMHh3Wxn79ASF.items.1.subItems.5'],
    disposition: 'do_not_self_adjudicate_use_current_rules_service_or_referee',
  }] : [];
  return seal({ schema: 'strategy_independent_full_source_audit_v1', inputHash: input.hash,
    candidateHash: candidate.hash, policyHash: hash(candidate.policy), axis: candidate.axis,
    checkedFields: [...REVIEW_FIELDS], independentObservations: AUDIT_NOTES[candidate.axis],
    boundSources: sources, targetedCorrectionHash: candidate.correction.hash,
    modelReviewLifecycleHash: lifecycle.hash, knownSourceConflicts,
    fullCoverage: true, sourceReviewPassed: true, humanReviewed: false,
    canAffectRules: false, runtimeAccepted: false, trainingTruth: false });
}

