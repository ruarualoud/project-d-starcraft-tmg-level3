export function createGeneralStrategySeedV1({ sourceBinding, referenceHash }) {
  const contract = createStrategyContractV1({ scope: { family: 'general' }, sourceBinding, referenceHash });
  const policies = SEEDS.map(([axis, title, when, objective, decisionProcedure, a, aw, b, bw,
    response, adaptation, risk, reviseIf, requiredQueries]) => ({ axis, title, when: [when], objective,
    decisionProcedure, alternatives: [{ option: a, preferWhen: aw }, { option: b, preferWhen: bw }],
    opponentBranches: [{ response, adaptation }], risk, reviseIf, requiredQueries, ruleRefs: [], caseIds: [] }));
  return createStrategyLayerV1({ contract, draft: { policies } });
}
