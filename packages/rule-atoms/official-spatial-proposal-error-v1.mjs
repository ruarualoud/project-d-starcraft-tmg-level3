// Only conclusive checks on the supplied coordinates belong here. Missing
// inputs, release capabilities and exhausted searches remain evaluation errors.
const rejectionCodes = new Set([
  'MODEL_BASE_GEOMETRY_PLACEMENT_OUTSIDE_BATTLEFIELD',
  'MODEL_BASE_GEOMETRY_PLACEMENT_OVERLAP',
  'MODEL_BASE_GEOMETRY_ENEMY_SEPARATION_REQUIRED',
  'MODEL_BASE_GEOMETRY_COHERENCY_LINK_INVALID',
  'MODEL_BASE_GEOMETRY_WHOLLY_WITHIN_REQUIRED',
  'SELECTED_SPATIAL_PATH_EXCEEDS_SPEED',
  'SELECTED_SPATIAL_FULL_BASE_OUTSIDE_BATTLEFIELD',
  'SELECTED_SPATIAL_ROTATING_BASE_OUTSIDE_BATTLEFIELD',
  'SELECTED_SPATIAL_PATH_MODEL_CLEARANCE_INSUFFICIENT',
  'SELECTED_SPATIAL_PATH_MODEL_COLLISION',
  'SELECTED_SPATIAL_TERRAIN_ENDPOINT_UNSUPPORTED',
  'SELECTED_SPATIAL_DEPLOY_TERRAIN_BLOCKED',
  'SELECTED_SPATIAL_ENDPOINT_WITHIN_BURROWED_ENGAGEMENT_RANGE',
  'SELECTED_SPATIAL_TERRAIN_PATH_BLOCKED',
  'SELECTED_SPATIAL_GAP_INPUT_HOST_DERIVED',
  'RELOCATION_PATH_EXCEEDS_DISTANCE',
  'RELOCATION_FULL_BASE_OUTSIDE_BATTLEFIELD',
  'RELOCATION_PATH_MODEL_COLLISION',
  'RELOCATION_TERRAIN_PATH_BLOCKED',
  'RELOCATION_TERRAIN_ENDPOINT_UNSUPPORTED',
  'RELOCATION_ENEMY_GAP_REQUIRED',
  'RELOCATION_EDGE_DISTANCE_EXCEEDED',
  'RELOCATION_ENTRY_SEGMENT_EXCEEDED',
  'RELOCATION_FRIENDLY_ANCHOR_DISTANCE_EXCEEDED',
  'RELOCATION_ENEMY_ZONE_OF_INFLUENCE_PROHIBITED',
  'RELOCATION_PLACE_DISTANCE_EXCEEDED',
]);

export function isOfficialSpatialRejectionCodeV1(code) {
  return rejectionCodes.has(code);
}

export class OfficialSpatialProposalRejectionV1 extends Error {
  constructor(code, message) {
    super(message);
    this.reasonCode = code;
  }
}

export function officialSpatialRuleErrorV1(code, detail) {
  const message = detail ? `${code}:${detail}` : code;
  return rejectionCodes.has(code) ? new OfficialSpatialProposalRejectionV1(code, message) : new Error(message);
}
