import { hashStarcraftTmgContract as hash } from '../authoritative-engine/referee-crypto-v1.mjs';
import { verifyOfficialAbilityEffectIrCatalogueV1 } from '../source-data/official-ability-effect-ir-v1.mjs';

const bloatedId = 'unit:ravager/bloated-bile-ducts-any-phase@1';
const potentId = 'unit:ravager/potent-bile-assault-phase@1';
const adapterId = 'official-characteristic-status-family-adapter-v1';
const sourceSpecs = [
  { definitionId: bloatedId, name: 'Bloated Bile Ducts', phase: 'any',
    text: `Increase the area of effect of this Unit's Corrosive Bile ability to 2".` },
  { definitionId: potentId, name: 'Potent Bile', phase: 'assault',
    text: "Before an Enemy Unit resolves an Armour Roll against the HITS effect generated by this Unit's Corrosive Bile ability, that Unit suffers DEBUFF Armour (1)." },
];
const without = (value, field) => Object.fromEntries(Object.entries(value).filter(([key]) => key !== field));
const seal = (value, field) => ({ ...value, [field]: hash(value) });

export function createOfficialCorrosiveBileUpgradeSourceV1({ context, catalogue, definitionIds }) {
  verifyOfficialAbilityEffectIrCatalogueV1(catalogue);
  if (!Array.isArray(definitionIds) || !definitionIds.length
    || new Set(definitionIds).size !== definitionIds.length
    || definitionIds.some(id => !sourceSpecs.some(spec => spec.definitionId === id))) {
    throw Error('CORROSIVE_BILE_UPGRADE_DEFINITIONS_INVALID');
  }
  const routes = [...definitionIds].sort().map(id => {
    const spec = sourceSpecs.find(row => row.definitionId === id);
    const definition = catalogue.definitions.find(row => row.definitionId === id);
    if (!definition || definition.recordKey !== 'army_units:ravager'
      || definition.definitionName !== spec.name || definition.phase !== spec.phase
      || definition.activationKind !== 'passive' || definition.sourceText !== spec.text) {
      throw Error('CORROSIVE_BILE_UPGRADE_SOURCE_UNSUPPORTED');
    }
    return { definitionId: id, abilityName: spec.name, sourceFeatureHash: definition.sourceFeatureHash, runtimeRole: definition.runtimeRole,
      sourceText: spec.text, costByComposition: definition.costByComposition };
  });
  const glossary = context.dataset.recordsByKey['rules_sections:FuahgilWtc8nccVSp2Vv'];
  const abilities = context.dataset.recordsByKey['rules_sections:H3Fn8YSvEvpJZpT57qw1'];
  const debuff = glossary?.payload.items[0].subItems.find(row => row.title === 'DEBUFF [Characteristic] (X)');
  if (!debuff?.content[0].value.includes('End of the Round')
    || !abilities?.payload.items[1].content[0].value.includes('their effects do not stack')
    || !abilities.payload.items[3].content[0].value.includes('as long as the Unit is on the battlefield')) {
    throw Error('CORROSIVE_BILE_UPGRADE_RULE_SOURCE_REQUIRED');
  }
  return seal({ schema: 'starcraft_tmg_corrosive_bile_upgrade_source_v1', version: '1.0.0', routes,
    sourceCatalogueHash: catalogue.catalogueHash, sourceSnapshotHash: catalogue.sourceSnapshotHash,
    normalizedDatasetHash: catalogue.normalizedDatasetHash,
    glossaryPayloadHash: glossary.payloadHash, abilityRulesPayloadHash: abilities.payloadHash,
    areaRangeMilliInches: 2000, armourPenalty: 1,
    sameNamedEffectsStack: false, passiveRequiresLiveFieldedSource: true,
    debuffExpiresAt: 'cleanup_and_refresh', trainingTruth: false }, 'bundleHash');
}

function verifySource(source) {
  if (!source || source.schema !== 'starcraft_tmg_corrosive_bile_upgrade_source_v1'
    || source.bundleHash !== hash(without(source, 'bundleHash')) || source.areaRangeMilliInches !== 2000
    || source.armourPenalty !== 1 || source.sameNamedEffectsStack !== false) {
    throw Error('CORROSIVE_BILE_UPGRADE_SOURCE_INVALID');
  }
  return source;
}

export function inspectOfficialCorrosiveBileUpgradesV1(state, pieceId) {
  const source = verifySource(state.officialCorrosiveBileUpgradeSourceBundle);
  const actor = state.pieces.find(piece => piece.id === pieceId);
  const active = actor?.officialUnitRecordKey === 'army_units:ravager' && actor.isOnField === true
    && actor.isDestroyed !== true && actor.models.some(model => model.isOnField !== false && model.isDestroyed !== true)
    && Number(actor.structureRules?.specialAbilitiesDisabledThroughRound ?? -1) < Number(state.round);
  const routes = active ? source.routes.filter(route => actor.selectedUpgradeNames?.includes(route.abilityName)) : [];
  return { sourcePieceId: pieceId, passiveSourceActive: active,
    effectRangeMilliInches: routes.some(route => route.definitionId === bloatedId) ? source.areaRangeMilliInches : 1000,
    potent: routes.find(route => route.definitionId === potentId) || null,
    applicableDefinitionIds: routes.map(route => route.definitionId), sourceBundleHash: source.bundleHash };
}

// The queue owns source/target identity. Call this immediately before opening
// the target's HITS pool so both the armour query and Native roll see it.
export function applyOfficialPotentBileDebuffV1(state, sourcePieceId, targetPieceId, effectHash) {
  const modifier = inspectOfficialCorrosiveBileUpgradesV1(state, sourcePieceId);
  const actor = state.pieces.find(piece => piece.id === sourcePieceId);
  const target = state.pieces.find(piece => piece.id === targetPieceId);
  if (!modifier.potent || actor.sideKey === target.sideKey) return [];
  if ((target.statuses || []).some(status => status.sourceDefinitionId === potentId)) {
    inspectOfficialPotentBileArmourPenaltyV1(state, target);
    return [];
  }
  const status = seal({ schema: 'starcraft_tmg_official_characteristic_status_effect_v1',
    sourceAdapterId: adapterId, sourceDefinitionId: potentId, sourceFeatureHash: modifier.potent.sourceFeatureHash,
    upgradeSourceBundleHash: modifier.sourceBundleHash,
    sourceSideKey: actor.sideKey, sourcePieceId, targetPieceId, sourceEffectHash: effectHash,
    statusKind: 'debuff', statusName: 'DEBUFF Armour (1)', characteristic: 'armour', modifier: -1,
    roundApplied: Number(state.round), expiresAt: 'cleanup_and_refresh', trainingTruth: false }, 'statusEffectHash');
  target.statuses = [...(target.statuses || []), status];
  const marker = seal({ schema: 'starcraft_tmg_official_characteristic_status_marker_v1',
    id: 'status-marker-' + status.statusEffectHash.slice(0,24), markerType: 'debuff',
    label: status.statusName, targetPieceId, sourceDefinitionId: potentId,
    statusEffectHash: status.statusEffectHash, expiresAt: status.expiresAt, trainingTruth: false }, 'markerHash');
  state.board.effectMarkers = [...(state.board.effectMarkers || []), marker];
  return [{ type: 'potent_bile_armour_debuff_applied', sourcePieceId, targetPieceId,
    sourceDefinitionId: potentId, statusEffectHash: status.statusEffectHash, expiresAt: status.expiresAt }];
}

export function inspectOfficialPotentBileArmourPenaltyV1(state, piece) {
  const statuses = (piece.statuses || []).filter(status => status.sourceDefinitionId === potentId);
  if (!statuses.length) return 0;
  const source = verifySource(state.officialCorrosiveBileUpgradeSourceBundle);
  const route = source.routes.find(row => row.definitionId === potentId);
  for (const status of statuses) {
    if (!route || status.statusEffectHash !== hash(without(status, 'statusEffectHash'))
      || status.upgradeSourceBundleHash !== source.bundleHash || status.sourceFeatureHash !== route.sourceFeatureHash
      || status.targetPieceId !== piece.id || status.sourceSideKey === piece.sideKey
      || status.characteristic !== 'armour' || status.modifier !== -1
      || status.roundApplied !== Number(state.round) || status.expiresAt !== source.debuffExpiresAt) {
      throw Error('POTENT_BILE_ARMOUR_STATUS_INVALID');
    }
  }
  return source.armourPenalty;
}
