import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import * as edits from '../packages/roster-strategist/roster-plan-edit-tools-v1.mjs';
import { assertStarcraftTmgProviderJsonSchemaSubsetV1 as strict } from '../packages/structured-generation/output-contract-registry-v1.mjs';
import {rosterInterruptedEditDraftV1,createRosterPlanEditRecoveryPortV1} from '../packages/roster-strategist/roster-plan-edit-recovery-v1.mjs';
const saved = JSON.parse(await fs.readFile(process.argv[2], 'utf8'));
const failed = saved.failedProviderOutputs.at(-1);
assert.equal(failed.providerIncompleteReason, 'max_output_tokens');
assert.ok((failed.rawText.match(/"F1392"/g) || []).length > 100);
const paths = ['deploymentConcept.threatTradeText', 'deploymentConcept.reinforcementPolicyText'];
const plan = {planHash:'a'.repeat(64),planVersion:4};
const factPacket = {sourceCatalogueHash:'b'.repeat(64),sourceFacts:{original:'unchanged'},
  premiseFacts:{numbers:[],texts:[{sourcePath:'original',text:'unchanged'}]}};
const make = protocol => edits.createRosterPlanEditToolsV1({plan,paths,factPacket,protocol});
const editor = make(edits.STRUCTURED_PLAN_TOOLS_PROTOCOL_V3 || edits.STRUCTURED_PLAN_TOOLS_PROTOCOL_V2);
const descriptor = editor.descriptor();
assert.ok(!descriptor.tools[0].inputSchema.properties.factIds,
  'Actual342 exhausted32K output repeating machine citation IDs; new editor must not ask model to copy them');
assert.equal(descriptor.sourceBinding.sourceCatalogueHash, factPacket.sourceCatalogueHash);
assert.equal(descriptor.semanticReviewStillRequired, true);
assert.ok(!descriptor.factCatalogue, 'No second 1MB ID catalogue when source facts already supplied');
strict(editor.outputContract({allowEvidenceReads:true}).contract.providerSchema);
const args = {claimPath:paths[0],intentText:'Goal',actionsText:'Actions',reasonText:'Reason',alternativesText:'Alternative',conditionsText:'Conditions'};
const result = editor.callTool({name:'plan.fill_argument',arguments:args});
assert.equal(result.isError,false);
assert.equal(editor.snapshot().applied,false);
assert.deepEqual(editor.snapshot().missingClaimPaths,[paths[1]]);
assert.equal(editor.snapshot().sourceBinding.sourceCatalogueHash,factPacket.sourceCatalogueHash);
assert.ok(!editor.snapshot().repairs[0].replacementText.includes('工具事实'));
assert.equal(make(edits.STRUCTURED_PLAN_TOOLS_PROTOCOL_V2).descriptor().tools[0].inputSchema.required.includes('factIds'),true);
assert.equal(make(edits.STRUCTURED_PLAN_TOOLS_PROTOCOL_V1).descriptor().tools[0].inputSchema.required.includes('factIds'),true);
const preview=rosterInterruptedEditDraftV1(failed);
assert.ok(preview.incompletePublicDraft.includes('threatTradeText'));
assert.ok(!preview.incompletePublicDraft.includes('"factIds":'));
assert.equal(preview.applied,false);
assert.equal(rosterInterruptedEditDraftV1({...failed,rawText:failed.rawText+'changed'}),null);
assert.equal(rosterInterruptedEditDraftV1({...failed,providerIncompleteReason:'unknown'}),null);
let calls=0;
const port=createRosterPlanEditRecoveryPortV1({port:{deliberate:async()=>{calls++;return 'live';}},retainedIncompleteOutputs:[failed]});
const req={roundIndex:failed.roundIndex,contextHash:failed.contextHash,responseFormat:{outputContractRef:failed.outputContractRef}};
await assert.rejects(()=>port.deliberate(req),e=>e.replayedFailure===true && e.failedOutputRecord.rawText===failed.rawText);
assert.equal(calls,0);
assert.equal(await port.deliberate({...req,contextHash:'c'.repeat(64)}),'live');
assert.equal(calls,1);
const limited=editor.outputContract({allowEvidenceReads:true,maxBatchSize:1});
strict(limited.contract.providerSchema);
assert.equal(limited.contract.providerSchema.properties.toolCalls.maxItems,1);
