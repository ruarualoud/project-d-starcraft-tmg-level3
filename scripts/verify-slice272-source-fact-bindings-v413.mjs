import fs from 'node:fs/promises';
import {gunzipSync} from 'node:zlib';
import assert from 'node:assert/strict';
import {inspectRosterTeachReaderCitationsV1,qualifyRosterTeachFrameworkSynthesisV1} from '../packages/roster-strategist/roster-teach-framework-v1.mjs';
const d=JSON.parse(await fs.readFile(process.argv[2],'utf8'));
const reply=JSON.parse(gunzipSync(await fs.readFile(process.argv[3])).toString()).output;
const context=d.teachFramework.context,original=JSON.stringify(context);
const answer=reply.answers.find(a=>a.questionId==='q-timing-round4-committed');
const feedback=inspectRosterTeachReaderCitationsV1({answers:[answer],evidence:[],sourceEvidence:context});
assert.equal(feedback.correctableFailures.length,0,'Actual200 cites the exact delivered scheduleHash and fields; source facts must have a shared citation identity');
const {collectRosterTeachSourceFactsV1}=await import('../packages/roster-strategist/roster-teach-source-facts-v1.mjs');
const facts=collectRosterTeachSourceFactsV1(context);
const row=facts.find(f=>f.value.ownerUnitId==='medic-1'&&f.value.partnerUnitId==='goliath-1');
assert(row);
const partner=reply.answers.find(a=>a.questionId==='q-capability-life-support-goliath');
const ambiguous=inspectRosterTeachReaderCitationsV1({answers:[partner],evidence:[],sourceEvidence:context});
assert(ambiguous.correctableFailures.some(f=>f.code==='ROSTER_TEACH_EVIDENCE_RECEIPT_UNKNOWN'),'A shared ability route hash cannot identify one partner-specific conclusion');
const specific={...partner,evidenceRefs:[row.citationRef],qualitativeEvidence:[{...partner.qualitativeEvidence[0],receiptRef:row.citationRef}]};
const output=qualifyRosterTeachFrameworkSynthesisV1({synthesis:{answers:[specific],proposedPlanChanges:[],proposedRosterChanges:[],frameworkFeedback:[]},evidence:[],sourceEvidence:context});
assert.equal(output.answers[0].qualitativeEvidence[0].value,'required_tag_mismatch');
assert.equal(output.answers[0].qualitativeEvidence[0].bindingView,'frozen_source_fact');
assert.equal(output.answers[0].qualitativeEvidence[0].interpretationVerified,false);
assert.equal(JSON.stringify(context),original);
console.log(JSON.stringify({passed:true,actualReply:200,scheduleBindings:5,ambiguousAbilityRouteRejected:true,exactPartnerBound:true,providerCalls:0}));
