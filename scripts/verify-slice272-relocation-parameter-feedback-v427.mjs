import fs from 'node:fs/promises';
import {gunzipSync} from 'node:zlib';
import assert from 'node:assert/strict';
import {inspectStarcraftTmgActionParametersV1,compileStarcraftTmgActionParameterContractV1} from '../packages/online-agent-session/action-parameter-contract-v1.mjs';
import {describeStarcraftTmgActionParameterRepairContextV1} from '../packages/online-agent-session/room-backed-spatial-rules-query-adapter-v1.mjs';
import {projectRosterTeachPromptEvidenceV1} from '../packages/roster-strategist/roster-teach-framework-v1.mjs';
const read=async n=>JSON.parse(gunzipSync(await fs.readFile(process.argv[2]+'/'+n)));
const input=await read('call-223.product-request.json.gz'),reply=await read('call-222.reply.json.gz');
const receipt=input.promptNodes.find(n=>n.kind==='fact_probe_tool_executions').currentBatchEvidence[0];
const query=JSON.parse(reply.output.queries[0].toolRequestJson),args=JSON.parse(query.argumentsJson);
const domain=receipt.queryRepair.actionSpace.parameterDomains.find(d=>d.domainId===args.domainId);
const before=JSON.stringify({input,reply});
assert.equal(receipt.unknownReasonCode,'RELOCATION_PLACEMENT_DENOMINATOR_INVALID');
const check=inspectStarcraftTmgActionParametersV1(domain,args.parameters);
assert.equal(check.valid,false,'Actual eight placements must be rejected by the same nine-model submission contract before Native');
const contract=compileStarcraftTmgActionParameterContractV1(domain);
assert.equal(contract.fieldContracts.placements.includesLeadingModel,true);
assert.equal(contract.fieldContracts.placements.minItems,9);
assert.equal(contract.fieldContracts.placements.maxItems,9);
const feedback=describeStarcraftTmgActionParameterRepairContextV1(domain,args,'RELOCATION_PLACEMENT_DENOMINATOR_INVALID','marine-1');
assert.equal(feedback.requiredPlacementCount,9);
assert.equal(feedback.submittedPlacementCount,8);
assert.equal(feedback.placementsIncludeLeadingModel,true);
assert.deepEqual(feedback.missingPlacementModelIds,['marine-1-model-1']);
assert.equal(feedback.requiredRemainingPlacementCount,null,'Relocation does not use ordinary movement remaining-model semantics');
assert.equal(feedback.submittedDistanceIncludingHostStartMilliInches,null,'No known native start must not produce a fictional zero path');
const complete=structuredClone(args.parameters);
complete.placements.push({modelId:complete.leadingModelId,...complete.path[0]});
assert.equal(inspectStarcraftTmgActionParametersV1(domain,complete).valid,true,'Transport shape only, not geometry proof');
complete.placements[8].modelId=complete.placements[0].modelId;
assert.equal(inspectStarcraftTmgActionParametersV1(domain,complete).valid,false,'Duplicate identity rejected');
const ordinary={parameterKind:'official_selected_roster_spatial_path_v1',actionType:'move',parameterSchema:{required:['leadingModelId','path','placements']},constraints:{modelProfiles:[{modelId:'a'},{modelId:'b'}]}};
const ordinaryFeedback=describeStarcraftTmgActionParameterRepairContextV1(ordinary,{parameters:{leadingModelId:'a',path:[],placements:[]}},'X',null);
assert.equal(ordinaryFeedback.requiredRemainingPlacementCount,1);
const projected=projectRosterTeachPromptEvidenceV1({kind:'fact_probe_tool_executions',currentBatchEvidence:[receipt]});
assert.deepEqual(projected.currentBatchEvidence[0],receipt,'Historical signed result stays unchanged');
assert.equal(projected.currentParameterChecks[0].parameterCheck.valid,false);
assert.equal(projected.currentParameterChecks[0].parameterCheck.parameterContract.fieldContracts.placements.minItems,9);
assert.equal(JSON.stringify({input,reply}),before);
console.log(JSON.stringify({passed:true,actualReply:222,missingLeaderDiagnosed:true,originalsUnchanged:true,providerCalls:0,nativeCalls:0}));
