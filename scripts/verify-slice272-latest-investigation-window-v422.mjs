import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import {rosterTeachInvestigationWindowV1,resumeRosterTeachUnstartedInvestigationV1} from '../packages/roster-strategist/roster-teach-capability-guide-v1.mjs';
import {isRosterTeachReaderContinuationV1} from '../packages/roster-strategist/roster-teach-framework-v1.mjs';
import {hashStarcraftTmgContract as hash} from '../packages/authoritative-engine/referee-crypto-v1.mjs';
const d=JSON.parse(await fs.readFile(process.argv[2],'utf8'));
const state=d.teachFramework.state,before=hash(state);
assert.equal(state.investigation.factProbeContinuation.startRound,13);
assert.equal(state.investigation.recoveryReplanContinuation.startRound,5);
const current=rosterTeachInvestigationWindowV1(state);
assert.equal(current.start,13,'New arrival investigation must not reuse the old fire-query window at5');
assert.equal(current.limit,16);
assert.deepEqual(current.questionIds,state.investigation.factProbeContinuation.questionIds);
assert.equal(current.unstartedContinuation,true,'Legacy wrongly-completed flag must not swallow the unstarted window');
assert.equal(hash(state),before,'Window selection is read-only, no historical answer reset');
assert.equal(isRosterTeachReaderContinuationV1(state),false,'Unstarted investigation must not take the synthesis shortcut');
const resumed=structuredClone(state), history=hash(resumed.investigation.rounds);
assert.equal(resumeRosterTeachUnstartedInvestigationV1(resumed),true);
assert.equal(resumed.investigation.completed,false);
assert.equal(hash(resumed.investigation.rounds),history);
assert.equal(hash(resumed.calls),hash(state.calls));
assert.equal(hash(resumed.pendingModelCall),hash(state.pendingModelCall));
assert.equal(resumeRosterTeachUnstartedInvestigationV1(resumed),false,'Resume is idempotent');
const alreadyRan=structuredClone(state);
alreadyRan.investigation.rounds.push({completed:true});
assert.equal(resumeRosterTeachUnstartedInvestigationV1(alreadyRan),false,'Completed work is not reopened');
const newer=structuredClone(state);
newer.investigation.recoveryReplanContinuation.startRound=14;
assert.equal(rosterTeachInvestigationWindowV1(newer).start,14,'A later recovery remains the current owner');
console.log(JSON.stringify({passed:true,selectedStart:13,priorStart:5,assignedQuestions:current.questionIds,
  historyUnchanged:true,providerCalls:0,nativeCalls:0}));
