import fs from 'node:fs/promises';
import zlib from 'node:zlib';
import assert from 'node:assert/strict';
import {attachRosterGenerationQueryIssuesV1,rosterTeachInvestigationContractV1} from '../packages/roster-strategist/roster-teach-framework-v1.mjs';
import {prepareRosterTeachPremiseAuditV1} from '../packages/roster-strategist/roster-teach-source-review-v1.mjs';
const [formalFile,run]=process.argv.slice(2);
const formal=JSON.parse(await fs.readFile(formalFile,'utf8'));
const fw=formal.teachFramework, plan=JSON.parse(formal.planSerialized);
const state=Object.fromEntries(['agenda','evidence','generationQueryHandoffs','questionPremiseAudit'].map(k=>[k,structuredClone(fw.state[k])]));
const originals=JSON.stringify(state.evidence), auditOutput=JSON.stringify(state.questionPremiseAudit.output);
assert.equal(state.agenda.questions.length,24);
attachRosterGenerationQueryIssuesV1(state,fw.context.generationQueryOutcomes);
assert.equal(state.agenda.questions.length,21,'Three historical query failures must attach by identity, not append three duplicate questions');
assert.equal(new Set(state.agenda.questions.map(q=>q.questionId)).size,21);
assert.equal(JSON.stringify(state.evidence),originals);
assert.equal(JSON.stringify(state.questionPremiseAudit.output),auditOutput);
assert.equal(prepareRosterTeachPremiseAuditV1({state,sourceReview:fw.context.sourceReview,plan,previousInquiry:fw.context.previousInquiry}),null,'Removing only obsolete host duplicates must not repurchase the completed premise audit');
assert(rosterTeachInvestigationContractV1(state.agenda.questions.map(q=>q.questionId)).providerSchema);
const reply=JSON.parse(zlib.gunzipSync(await fs.readFile(`${run}/call-257.reply.json.gz`))).output;
const fresh={agenda:structuredClone(reply),evidence:[]};
attachRosterGenerationQueryIssuesV1(fresh,fw.context.generationQueryOutcomes);
assert.equal(fresh.agenda.questions.length,21,'Fresh generation must not create the duplicate in the first place');
assert.equal(fresh.generationQueryHandoffs.length,3);
assert.equal(fresh.evidence.length,3);
console.log(JSON.stringify({pass:true,existingQuestions:21,freshQuestions:21,oldFailureReceiptsRetained:3,priorAuditPreserved:true,providerCalls:0,nativeCalls:0}));
