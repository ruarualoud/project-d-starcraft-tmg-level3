import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {gunzipSync} from 'node:zlib';
import {rosterTeachInvestigationWindowV1} from '../packages/roster-strategist/roster-teach-capability-guide-v1.mjs';
import '../packages/roster-strategist/roster-teach-framework-v1.mjs';
const directory=process.argv[2];
const paid=JSON.parse(gunzipSync(await fs.readFile(path.join(directory,'call-170.product-request.json.gz'))));
const draft=JSON.parse(await fs.readFile(path.join(path.dirname(directory),'workspace/drafts',paid.sessionId+'.json'),'utf8'));
const saved=draft.teachFramework.state;
const failed=saved.queryRecovery.operations.find(op=>op.result?.unknownReasonCode==='CURRENT_ACTION_QUERY_DOMAIN_UNKNOWN');
assert(failed?.completed,'actual failed same-scene correction must be completed');
const state=structuredClone(saved);
delete state.pendingModelCall; // Evaluate after the unrelated paid171 is consumed.
state.queryRecovery.operations=[structuredClone(failed)];
const before=JSON.stringify(state);
const window=rosterTeachInvestigationWindowV1(state);
assert(window.questionIds.includes(failed.questionId),'completed narrow correction must return to investigator instead of synthesis');
assert.equal(window.recoveryReplan?.historyReset,false);
assert.equal(window.start,state.investigation.rounds.length);
assert.equal(JSON.stringify(state),before,'querying the window must not mutate durable state');
state.investigation.recoveryReplanHistory=[structuredClone(window.recoveryReplan)];
state.investigation.recoveryReplanContinuation=structuredClone(window.recoveryReplan);
state.investigation.completed=false;
assert.equal(rosterTeachInvestigationWindowV1(state).limit,window.start+1);
state.investigation.rounds.push({completed:true,output:{queries:[],questionProgress:[{questionId:failed.questionId,disposition:'plan_revision_required',evidenceQueryIds:[],publicReason:'original evidence refutes premise'}]}});
state.investigation.completed=true;
assert.equal(rosterTeachInvestigationWindowV1(state).recoveryReplan,undefined,'same question must not reopen forever');
assert.equal(rosterTeachInvestigationWindowV1(state).questionIds.length,0);
const answered=structuredClone(saved); delete answered.pendingModelCall; answered.queryRecovery.operations=[{...failed,result:{status:'exact'},status:'exact'}];
assert.equal(rosterTeachInvestigationWindowV1(answered).recoveryReplan,undefined);
console.log(JSON.stringify({passed:true,actualFailedQuery:failed.queryId,source:'paid-call170',sameQuestionHandoff:true,noHistoryReset:true,noRepeatLoop:true,providerCalls:0}));
