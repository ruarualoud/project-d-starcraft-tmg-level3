import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {gunzipSync} from 'node:zlib';
import path from 'node:path';
import {inspectStarcraftTmgActionParametersV1} from '../packages/online-agent-session/action-parameter-contract-v1.mjs';
const directory=process.argv[2];
const reply=JSON.parse(gunzipSync(await fs.readFile(path.join(directory,'call-175.reply.json.gz'))));
const request=JSON.parse(gunzipSync(await fs.readFile(path.join(directory,'call-175.product-request.json.gz'))));
const draft=JSON.parse(await fs.readFile(path.join(path.dirname(directory),'workspace/drafts',request.sessionId+'.json'),'utf8'));
const tool=JSON.parse(reply.output.queries[0].toolRequestJson),args=JSON.parse(tool.argumentsJson);
const branch=draft.teachFramework.state.investigation.evidence.find(e=>e.challengeId===tool.branchIdRef);
const domain=branch.branchQueryContext.actionSpace.parameterDomains.find(d=>d.domainId===args.domainId);
const before=JSON.stringify(domain);
const invalid=inspectStarcraftTmgActionParametersV1(domain,args.parameters);
assert.equal(invalid.valid,false,'real175 duplicate leader/count error must be found by shared submission contract');
assert(invalid.fieldIssues.some(issue=>issue.fieldPath==='parameters.placements'));
assert.equal(invalid.requiresReplan,false);
assert.equal(invalid.parameterContract.fieldContracts.placements.minItems,8);
assert.equal(invalid.parameterContract.fieldContracts.placements.maxItems,8);
assert.equal(invalid.parameterContract.fieldContracts.placements.excludesLeadingModel,true);
const corrected=structuredClone(args.parameters);
corrected.placements=corrected.placements.filter(p=>p.modelId!==corrected.leadingModelId);
assert.equal(inspectStarcraftTmgActionParametersV1(domain,corrected).valid,true,'parameter-valid is not a geometry approval');
corrected.placements[0].modelId=corrected.leadingModelId;
assert.equal(inspectStarcraftTmgActionParametersV1(domain,corrected).valid,false);
assert.equal(JSON.stringify(domain),before,'retained domain is described, not resealed');
console.log(JSON.stringify({passed:true,actualReply:175,sharedNativeSubmissionContract:true,notGeometryAcceptance:true,providerCalls:0}));
