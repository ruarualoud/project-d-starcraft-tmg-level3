import assert from 'node:assert/strict';
import { mkdtemp } from 'node:fs/promises';
import { openProductionStore } from '../packages/skill-production/store.mjs';
import { pausePacketRunAfterCurrentRole } from './support/packet-run-control-v1.mjs';
import { hash } from '../packages/skill-production/common.mjs';
const dir = await mkdtemp(new URL('../build/ticket-18-first-five-v1/pause-tests-', import.meta.url));
const filename = dir + '/state.sqlite', recipeHash = hash('fixture'), runId = 'rules-v2-' + recipeHash.slice(0, 20);
const store = openProductionStore(filename, { runId, recipeHash });
const lease = store.acquire('rules-reading-001.generator', { task: 'fixed' });
store.reserve('in-flight', {}, 500, 100);
const receipt = pausePacketRunAfterCurrentRole({ filename, runId, recipeHash });
assert.equal(pausePacketRunAfterCurrentRole({ filename, runId, recipeHash }).hash, receipt.hash);
assert.equal(store.summary().attempts[0].state, 'intent');
store.settle('in-flight', { usage: { inputUnits: 12, outputUnits: 4, totalUnits: 16 }, costMicros: 20, response: { ok: true } });
assert.throws(() => store.finish(lease, { output: 'late completion' }), e => e.code === 'STEP_LEASE_STALE');
store.release(lease);
assert.equal(store.summary().knownTokens, 16); assert.equal(store.summary().reservedOrSettledMicros, 20);
assert.equal(store.summary().steps.find(s => s.id === lease.id).state, 'pending');
const recovered = store.acquire(lease.id, { task: 'fixed' });
assert(store.reserve('in-flight', {}, 500, 100).cached);
store.finish(recovered, { output: 'recovered from exact paid response' });
assert.equal(store.summary().calls, 1); store.close();
console.log(JSON.stringify({ passed: true, checks: 8, providerCalls: 0 }));
