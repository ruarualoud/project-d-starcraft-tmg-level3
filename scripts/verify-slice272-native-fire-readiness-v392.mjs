import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {gunzipSync} from 'node:zlib';
import {assessRosterTeachEvidenceReadinessV1} from '../packages/roster-strategist/roster-teach-evidence-port-v1.mjs';
import {rosterTeachInvestigationWindowV1} from '../packages/roster-strategist/roster-teach-capability-guide-v1.mjs';
const directory=process.argv[2];
const paid=JSON.parse(gunzipSync(await fs.readFile(path.join(directory,'call-171.product-request.json.gz'))));
const draft=JSON.parse(await fs.readFile(path.join(path.dirname(directory),'workspace/drafts',paid.sessionId+'.json'),'utf8'));
const operation=draft.teachFramework.state.queryRecovery.operations.find(op=>op.originalQueryId==='teach-scenario-kerrigan-vs-goliath-fire-zone');
const actual=operation.result;
assert.equal(actual.status,'advisory');
assert.equal(actual.followUpReceipts[0].receipt.queryReceipt.result.attackEstimates.length,0);
const readiness=assessRosterTeachEvidenceReadinessV1(actual);
assert.equal(readiness.usableForClaim,false,'native fire empty result must not bypass dedicated-wrapper readiness');
assert(readiness.reasons.includes('NO_ATTACK_ESTIMATES_IN_SELECTED_SCENE'));
const state=structuredClone(draft.teachFramework.state);
delete state.pendingModelCall; state.investigation.completed=true;
state.queryRecovery.operations=[structuredClone(operation)];
const window=rosterTeachInvestigationWindowV1(state);
assert(window.recoveryReplan?.questionIds.includes(operation.questionId),'retained falsely-advisory result must return to investigation');
const nonempty=structuredClone(actual);
nonempty.followUpReceipts[0].receipt.queryReceipt.result.attackEstimates=[{estimateHash:'nonempty-native-result'}];
assert.equal(assessRosterTeachEvidenceReadinessV1(nonempty).usableForClaim,true);
console.log(JSON.stringify({passed:true,actualReply:171,emptyEstimateCannotBeLaunderedByToolAlias:true,savedFailureHandback:true,providerCalls:0}));
