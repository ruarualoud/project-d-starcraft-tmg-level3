import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import * as port from '../packages/roster-strategist/iterative-roster-flash-model-port-v1.mjs';
import {projectRosterTeachPromptEvidenceV1} from '../packages/roster-strategist/roster-teach-framework-v1.mjs';
import {readIterativeRosterTeachEvidenceV1} from '../packages/roster-strategist/iterative-roster-plan-session-v1.mjs';
const state=JSON.parse(await fs.readFile(process.argv[2],'utf8')).value;
const original=JSON.stringify(state.teachFeedback);
const old=projectRosterTeachPromptEvidenceV1(state.teachFeedback);
assert(JSON.stringify(old).length>3_000_000,'Actual210 feedback alone is several MB');
assert.equal(typeof port.projectIterativeRosterTeachDecisionFeedbackV1,'function',
 'Actual210 re-inlines completed investigation and ~2MB old premiseFacts in a 5MB decision request despite an existing original-read tool');
const next=port.projectIterativeRosterTeachDecisionFeedbackV1(state.teachFeedback);
assert(JSON.stringify(next).length<JSON.stringify(old).length/3,'Keep current decision material, retrieve old evidence by address');
assert.deepEqual(next.teachFramework.synthesis,old.teachFramework.synthesis);
assert.deepEqual(next.acceptanceIssues,old.acceptanceIssues);
assert.deepEqual(next.taughtPlan,projectRosterTeachPromptEvidenceV1(state.teachFeedback.taughtPlan));
assert.deepEqual(next.sourceReview.review.findings,projectRosterTeachPromptEvidenceV1(state.teachFeedback.sourceReview.review.findings));
assert.deepEqual(next.sourceReview.review.reviewAdjudication.decisions,state.teachFeedback.sourceReview.review.reviewAdjudication.decisions);
const ref=next.sourceReview.review.reviewAdjudication.reconciliation.premiseFacts;
assert.equal(ref.readOnly,true);
const request=JSON.parse(ref.retrieval.argumentsJson);
const result=readIterativeRosterTeachEvidenceV1(state,request);
assert.equal(result.status,'advisory');
assert(result.result.fullBodyAvailable||Object.hasOwn(result.result,'value'));
const synthRef=next.teachFramework.investigation;
const evidenceRead=readIterativeRosterTeachEvidenceV1(state,JSON.parse(synthRef.retrieval.argumentsJson));
assert.equal(evidenceRead.status,'advisory','No inaccessible archive references');
assert.equal(JSON.stringify(state.teachFeedback),original,'Original records not changed');
console.log(JSON.stringify({passed:true,actualRequest:210,beforeBytes:JSON.stringify(old).length,afterBytes:JSON.stringify(next).length,answers:next.teachFramework.synthesis.answers.length,proposals:next.teachFramework.synthesis.proposedPlanChanges.length,allOriginalsReadable:true,providerCalls:0}));
